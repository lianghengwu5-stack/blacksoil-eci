 def cite(self,text):
  def convert(m):
   numbers=[]
   for key in m.group(1).split(','):
    assert key in REF,key
    if key not in self.refs:self.refs.append(key)
    numbers.append(str(self.refs.index(key)+1))
   return '['+','.join(sorted(numbers,key=int))+']'
  text=re.sub(r'。\s*(\{ref:[^}]+\})',r'\1。',text)
  return re.sub(r'\{ref:([^}]+)\}',convert,text)
 def p(self,text,style=None):
  text=self.cite(text);p=self.d.add_paragraph(text,style);self.content.append({'type':'text','text':text});return p
